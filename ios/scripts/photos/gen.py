"""Builds the app's and server's lists of hand-picked Unsplash photos from picks.json, and bundles the welcome photos.

Run from the repository root: python3 ios/scripts/photos/gen.py
- ios/TripIt/Design/ScenePhotos.swift: the photo for each place the app features (WorldScenes ids), and a few cities.
- backend/app/data/city_photos.json: the same with each place's names, so the server can pick a trip's cover photo.
- ios/TripIt/Assets.xcassets/Photo-<id>.imageset: the welcome screen's photos, in the app so they show offline at once.
Photos from Unsplash are free to use; the app shows each photographer's name where a photo is shown large.
"""
import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
picks = json.loads((Path(__file__).parent / "picks.json").read_text())
swift = (ROOT / "ios/TripIt/Design/WorldScenes.swift").read_text()
scenes = {m[0]: (m[1], json.loads("[" + m[2] + "]")) for m in
          re.findall(r'id: "([a-zA-Z]+)", place: "([^"]+)", names: \[([^\]]*)\]', swift)}
missing = set(scenes) - set(picks["scenes"])
assert not missing, f"no photo picked for {missing}"


def entry(p: list[str]) -> str:
    return f'ScenePhoto(photo: "{p[0]}", name: "{p[1]}", username: "{p[2]}")'


lines = ["// Generated by ios/scripts/photos/gen.py from picks.json: don't edit by hand.", "import Foundation", "",
         "enum ScenePhotos {", "    /// The photo for each featured place (WorldScenes ids).", "    static let scenes: [String: ScenePhoto] = ["]
lines += [f'        "{k}": {entry(v)},' for k, v in sorted(picks["scenes"].items())]
lines += ["    ]", "", "    /// Cities with a photo of their own (otherwise a city gets its featured place's, or one found for it).",
          "    static let cities: [String: ScenePhoto] = ["]
lines += [f'        "{k}": {entry(v)},' for k, v in sorted(picks["cities"].items())]
lines += ["    ]", "", "    /// In the app itself (Photo-<id> in the asset catalogue), so the welcome screen shows them offline at once.",
          "    static let bundled: Set<String> = [" + ", ".join(f'"{b}"' for b in picks["bundled"]) + "]", "}", ""]
(ROOT / "ios/TripIt/Design/ScenePhotos.swift").write_text("\n".join(lines))

server = {"places": [{"id": k, "place": scenes[k][0], "names": scenes[k][1], "photo": v[0], "name": v[1], "username": v[2]}
                     for k, v in sorted(picks["scenes"].items())],
          "cities": {k: {"photo": v[0], "name": v[1], "username": v[2]} for k, v in sorted(picks["cities"].items())}}
(ROOT / "backend/app/data").mkdir(exist_ok=True)
(ROOT / "backend/app/data/city_photos.json").write_text(json.dumps(server, ensure_ascii=False, indent=1) + "\n")

for sid in picks["bundled"]:
    folder = ROOT / f"ios/TripIt/Assets.xcassets/Photo-{sid}.imageset"
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / f"Photo-{sid}.jpg"
    if not target.exists():
        url = f"https://images.unsplash.com/{picks['scenes'][sid][0]}?w=1080&h=1920&fit=crop&crop=entropy&q=72&fm=jpg"
        target.write_bytes(urllib.request.urlopen(url, timeout=30).read())
    (folder / "Contents.json").write_text(json.dumps(
        {"images": [{"filename": target.name, "idiom": "universal"}], "info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
print(f"{len(picks['scenes'])} places, {len(picks['cities'])} cities, {len(picks['bundled'])} bundled")
